function makeProduct(data: Partial<Product> & { name: string; price: number; category_id: string; image: string }): Product {
  const mrp = data.mrp ?? Math.round(data.price * (data.discount != null ? 100 / (100 - data.discount) : 1.22));
  const discount = data.discount ?? Math.round(((mrp - data.price) / mrp) * 100);
  const slug = data.slug ?? data.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  const cat = mockCategories.find((c) => c.id === data.category_id);
  return {
    id: data.id ?? pid(),
    slug,
    name: data.name,
    description: data.description ?? `${data.name} — premium quality, engineered for durability, available at DIA Enterprises.`,
    short_description: data.short_description,
    price: data.price,
    mrp,
    gst: data.gst ?? 18,
    discount,
    category_id: data.category_id,
    category_name: cat?.name,
    brand_id: data.brand_id ?? "brand-dia",
    brand_name: data.brand_name ?? "DIA Premium",
    sku: data.sku ?? `PE-${Math.random().toString(36).slice(2, 8).toUpperCase()}`,
    stock_quantity: data.stock_quantity ?? 250,
    unit: data.unit ?? "per sq. ft.",
    images: [data.image],
    colors: data.colors ?? [],
    sizes: data.sizes ?? [],
    thickness: data.thickness ?? [],
    material: data.material ?? "PVC",
    specifications: data.specifications ?? {},
    features: data.features ?? [],
    tags: data.tags ?? [],
    is_featured: data.is_featured ?? false,
    is_best_seller: data.is_best_seller ?? false,
    is_new_arrival: data.is_new_arrival ?? false,
    is_published: data.is_published ?? true,
    views: data.views ?? 100,
    sold: data.sold ?? 40,
    seo_title: data.seo_title,
    seo_description: data.seo_description,
    created_at: data.created_at ?? daysAgo(100),
    updated_at: daysAgo(5),
  };
}

